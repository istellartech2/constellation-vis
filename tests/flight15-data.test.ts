import { describe, expect, it } from "bun:test";
import { readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import * as THREE from "three";
import { parseTrajectoryFile, toTrajectoryTrack } from "../src/lib/trajectory/parse";
import { trajectoryStateAt } from "../src/lib/trajectory/interpolate";
import { geodeticUpEcef, trajectoryAttitudeAt } from "../src/lib/trajectory/attitude";
import type { TrajectoryTrack } from "../src/lib/trajectory/types";
import { BOOSTER_END, BOOSTER_LENGTH_M, PAD, SHIP_LENGTH_M, axisGapM, groundDistanceKm, speedOfSound } from "../scripts/analysis/flight15-reconstruct";

// Data contract of the Flight 15 demo (public/demos/flight15/*.csv, generated by
// scripts/analysis/flight15-reconstruct.ts). Published times are hard-coded here
// on purpose, so a change in the generator cannot silently move them.

const DIR = join(import.meta.dir, "..", "public", "demos", "flight15");
const EPOCH_MS = Date.parse("2026-11-13T22:47:36Z");
const OMEGA = 7.292115e-5;
const RE = 6378.137;
const hms = (h: number, m: number, s: number) => h * 3600 + m * 60 + s;
const G = 9.80665e-3; // km/s^2
type V = [number, number, number];

function load(file: string): { track: TrajectoryTrack; warnings: string[] } {
  const res = parseTrajectoryFile(readFileSync(join(DIR, file), "utf8"), file);
  if (!res.ok) throw new Error(res.error);
  return { track: toTrajectoryTrack(res.track, 0), warnings: res.warnings };
}
const booster = load("booster.csv");
const ship = load("ship.csv");
const at = (track: TrajectoryTrack, t: number) => {
  const s = trajectoryStateAt(track, EPOCH_MS + t * 1000);
  if (!s) throw new Error(`no state at T+${t}`);
  return s;
};
const lastT = (track: TrajectoryTrack) => (track.samples[track.samples.length - 1].timeMs - EPOCH_MS) / 1000;
function noseElevationDeg(track: TrajectoryTrack, t: number): number {
  const s = at(track, t);
  const q = trajectoryAttitudeAt(track, EPOCH_MS + t * 1000, s);
  if (!q) throw new Error("no attitude");
  const nose = new THREE.Vector3(1, 0, 0).applyQuaternion(new THREE.Quaternion(q.x, q.y, q.z, q.w));
  const up = geodeticUpEcef(s.latDeg, s.lonDeg, new THREE.Vector3());
  return (Math.asin(Math.max(-1, Math.min(1, nose.dot(up)))) * 180) / Math.PI;
}
function noseEcef(track: TrajectoryTrack, t: number): THREE.Vector3 {
  const s = at(track, t);
  const q = trajectoryAttitudeAt(track, EPOCH_MS + t * 1000, s)!;
  return new THREE.Vector3(1, 0, 0).applyQuaternion(new THREE.Quaternion(q.x, q.y, q.z, q.w));
}
const pos = (track: TrajectoryTrack, t: number): V => {
  const p = at(track, t).position;
  return [p.x, p.y, p.z];
};
const vec = (v: THREE.Vector3): V => [v.x, v.y, v.z];
/** Separation as drawn: minimum distance (m) between the booster body and the ship body (both from their bases along their noses). */
const gapM = (t: number) =>
  axisGapM(pos(booster.track, t), vec(noseEcef(booster.track, t)), BOOSTER_LENGTH_M, pos(ship.track, t), vec(noseEcef(ship.track, t)), SHIP_LENGTH_M);
/** Acceleration (km/s^2, ECEF) by central differences of the interpolated velocity, split into local up / horizontal parts. */
function accelAt(track: TrajectoryTrack, t: number, h: number) {
  const a = at(track, t - h).velocity;
  const b = at(track, t + h).velocity;
  const acc = new THREE.Vector3((b.x - a.x) / (2 * h), (b.y - a.y) / (2 * h), (b.z - a.z) / (2 * h));
  const s = at(track, t);
  const up = geodeticUpEcef(s.latDeg, s.lonDeg, new THREE.Vector3());
  const vel = new THREE.Vector3(s.velocity.x, s.velocity.y, s.velocity.z);
  const vh = vel.clone().addScaledVector(up, -vel.dot(up));
  const av = acc.dot(up);
  const ah = acc.clone().addScaledVector(up, -av);
  // lateral = horizontal acceleration perpendicular to the horizontal velocity (+ = right turn)
  const side = vh.lengthSq() > 0 ? vh.clone().normalize().cross(up) : new THREE.Vector3();
  return { av, ah: ah.length(), lat: -ah.dot(side), vh: vh.length() };
}
const maxStep = (track: TrajectoryTrack, from: number, to: number) => {
  let worst = 0;
  const ts = track.samples.map((s) => (s.timeMs - EPOCH_MS) / 1000);
  for (let i = 1; i < ts.length; i += 1) if (ts[i] > from + 1e-9 && ts[i - 1] < to - 1e-9) worst = Math.max(worst, ts[i] - ts[i - 1]);
  return worst;
};

describe("Flight 15 demo data files", () => {
  it("parse without any warning and stay small", () => {
    expect(booster.warnings).toEqual([]);
    expect(ship.warnings).toEqual([]);
    const bytes = statSync(join(DIR, "booster.csv")).size + statSync(join(DIR, "ship.csv")).size;
    expect(bytes).toBeLessThan(1.5 * 1024 * 1024);
  });

  it("carry the shared epoch, models and attitude (no mount: the ship track is the ship's base)", () => {
    expect(booster.track.epochMs).toBe(EPOCH_MS);
    expect(ship.track.epochMs).toBe(EPOCH_MS);
    expect(booster.track.model).toBe("starship-v3-booster");
    expect(ship.track.model).toBe("starship-v3-ship");
    expect(ship.track.mount).toBeUndefined();
    expect(booster.track.attitudeRules.length).toBeGreaterThanOrEqual(4);
    expect(ship.track.samples.every((s) => s.attitude)).toBe(true);
  });

  it("place every event at its published time", () => {
    const ev = (track: TrajectoryTrack) => track.events.map((e) => [(e.timeMs - EPOCH_MS) / 1000, e.label]);
    expect(ev(booster.track)).toEqual([
      [0, "打上げ"],
      [58, "最大動圧"],
      [139, "1段エンジン停止"],
      [141, "ホットステージング（段の分離）"],
      [146, "ブーストバック開始"],
      [182, "ブーストバック終了"],
      [370, "着陸噴射"],
      [395, "キャッチ中止・洋上へ"],
    ]);
    expect(ev(ship.track)).toEqual([
      [0, "打上げ"],
      [58, "最大動圧"],
      [141, "ホットステージング（段の分離）"],
      [489, "2段エンジン停止"],
      [hms(0, 26, 10), "軌道投入噴射"],
      [hms(0, 35, 1), "Starlink 分離開始"],
      [hms(1, 17, 40), "Starlink 分離完了"],
      [hms(21, 35, 57), "軌道離脱噴射"],
      [hms(22, 10, 46), "大気圏再突入"],
      [hms(22, 30, 13), "音速以下へ減速"],
      [hms(22, 32, 16), "着陸噴射・フリップ"],
      [hms(22, 32, 28), "タワーでキャッチ"],
    ]);
  });

  it("stack the ship's base on top of the booster until hot staging", () => {
    // pad: booster base on the drawn ground (h = 0), ship base 72.3 m above it
    expect(Math.abs(at(booster.track, 0).altKm)).toBeLessThan(1e-6);
    expect(Math.abs(at(ship.track, 0).altKm - BOOSTER_LENGTH_M / 1000)).toBeLessThan(0.0005);
    for (const t of [0, 1, 10, 30, 58, 100, 139, 140, 140.5, 141]) {
      const b = pos(booster.track, t);
      const sp = pos(ship.track, t);
      const n = noseEcef(booster.track, t);
      const d = new THREE.Vector3(sp[0] - b[0], sp[1] - b[1], sp[2] - b[2]).multiplyScalar(1000);
      // ship base = booster base + booster nose (as drawn) · 72.3 m, within 0.5 m
      expect(d.distanceTo(n.clone().multiplyScalar(BOOSTER_LENGTH_M))).toBeLessThan(0.5);
      expect(gapM(t)).toBeLessThan(0.5);
    }
    const st = at(ship.track, 141);
    expect(st.altKm).toBeGreaterThan(55);
    expect(st.altKm).toBeLessThan(80);
    // stacked noses aligned during the ascent
    for (const t of [5, 30, 80, 130, 140]) expect(noseEcef(booster.track, t).angleTo(noseEcef(ship.track, t))).toBeLessThan((0.5 * Math.PI) / 180);
  });

  it("separates continuously at hot staging with a growing gap", () => {
    const gaps = [0.5, 1, 2, 3, 5, 7, 10, 15].map((dt) => gapM(141 + dt));
    for (let i = 1; i < gaps.length; i += 1) expect(gaps[i]).toBeGreaterThan(gaps[i - 1]);
    expect(gaps[0]).toBeGreaterThan(0.5); // never overlapping after separation
    expect(gapM(143)).toBeGreaterThan(5);
    expect(gapM(151)).toBeGreaterThan(200);
    // the ship's base moves away from the booster's top smoothly: no jump at separation
    const top = (t: number) => {
      const b = pos(booster.track, t);
      const n = noseEcef(booster.track, t).multiplyScalar(BOOSTER_LENGTH_M / 1000);
      return new THREE.Vector3(b[0] + n.x, b[1] + n.y, b[2] + n.z);
    };
    let prev = 0;
    for (let t = 141.25; t <= 146; t += 0.25) {
      const d = top(t).distanceTo(new THREE.Vector3(...pos(ship.track, t))) * 1000;
      expect(d).toBeGreaterThan(prev);
      prev = d;
    }
  });

  it("reach the published 276 × 278 km, 30.5° orbit after the insertion burn", () => {
    let rMin = Infinity;
    let rMax = -Infinity;
    let incSum = 0;
    let n = 0;
    for (let t = hms(0, 27, 0); t <= hms(1, 50, 0); t += 10) {
      const s = at(ship.track, t);
      const r = new THREE.Vector3(s.position.x, s.position.y, s.position.z);
      const vIn = new THREE.Vector3(s.velocity.x - OMEGA * r.y, s.velocity.y + OMEGA * r.x, s.velocity.z);
      const h = r.clone().cross(vIn);
      rMin = Math.min(rMin, r.length());
      rMax = Math.max(rMax, r.length());
      incSum += (Math.acos(h.z / h.length()) * 180) / Math.PI;
      n += 1;
    }
    expect(rMin - RE).toBeGreaterThan(274.5);
    expect(rMin - RE).toBeLessThan(277.5);
    expect(rMax - RE).toBeGreaterThan(276.5);
    expect(rMax - RE).toBeLessThan(279.5);
    expect(Math.abs(incSum / n - 30.5)).toBeLessThan(0.1);
  });

  it("re-enters at the entry interface and passes Mach 1.2 / 0.8 at the published times", () => {
    expect(Math.abs(at(ship.track, hms(22, 10, 46)).altKm - 100)).toBeLessThan(3);
    const mach = (t: number) => {
      const s = at(ship.track, t);
      return (s.speedKmS / speedOfSound(s.altKm));
    };
    expect(Math.abs(mach(hms(22, 29, 34)) - 1.2)).toBeLessThan(0.05);
    expect(Math.abs(mach(hms(22, 30, 13)) - 0.8)).toBeLessThan(0.05);
  });

  it("returns from the west, north of South Padre Island, turning south to the tower", () => {
    expect(at(ship.track, hms(22, 25, 0)).lonDeg).toBeLessThan(PAD.lonDeg - 1);
    // while crossing the coast (lon −97.19) the ship is north of South Padre Island town (≈26.10° N)
    let crossLat = NaN;
    for (let t = hms(22, 25, 0); t < hms(22, 32, 0); t += 0.5) {
      if (at(ship.track, t).lonDeg >= -97.19) {
        crossLat = at(ship.track, t).latDeg;
        break;
      }
    }
    expect(crossLat).toBeGreaterThan(26.2);
    // over the Gulf, heading south, north of the pad, during the belly flop
    const s = at(ship.track, hms(22, 31, 0));
    expect(s.latDeg).toBeGreaterThan(PAD.latDeg);
    expect(s.lonDeg).toBeGreaterThan(PAD.lonDeg);
    expect(s.velocity.z).toBeLessThan(0);
  });

  it("flies the final approach as one smooth, bank-limited turn", () => {
    // from the end of the physics entry (T+22:27:04) to the landing burn
    let maxLat = 0;
    let minRadiusKm = Infinity;
    let maxLatChange = 0;
    let prevLat = NaN;
    for (let t = hms(22, 27, 10); t <= hms(22, 32, 10); t += 1) {
      const a = accelAt(ship.track, t, 0.5);
      maxLat = Math.max(maxLat, Math.abs(a.lat));
      // radius of the turn proper (until the roll-out ends ~T+22:30:06), r = v²/a_lat = v²/(g·tan φ)
      if (t <= hms(22, 30, 0) && Math.abs(a.lat) > 0.1 * G) minRadiusKm = Math.min(minRadiusKm, (a.vh * a.vh) / Math.abs(a.lat));
      if (!Number.isNaN(prevLat)) maxLatChange = Math.max(maxLatChange, Math.abs(a.lat - prevLat));
      prevLat = a.lat;
    }
    expect(maxLat / G).toBeLessThan(0.5); // lateral load ≤ 0.5 g → bank ≤ 26.6°
    expect((Math.atan(maxLat / G) * 180) / Math.PI).toBeLessThan(30);
    // continuous heading rate: no kinks (a kink would step by the full ~0.4 g; ±0.03 g is interpolation ripple)
    expect(maxLatChange / G).toBeLessThan(0.08);
    expect(minRadiusKm).toBeGreaterThan(15);
    // final leg heading south-south-west toward the tower
    const s = at(ship.track, hms(22, 31, 0));
    const up = geodeticUpEcef(s.latDeg, s.lonDeg, new THREE.Vector3());
    const v = new THREE.Vector3(s.velocity.x, s.velocity.y, s.velocity.z);
    const east = new THREE.Vector3(0, 0, 1).cross(up).normalize();
    const north = up.clone().cross(east);
    const heading = (Math.atan2(v.dot(east), v.dot(north)) * 180) / Math.PI + 360;
    expect(Math.abs((heading % 360) - 195)).toBeLessThan(5);
  });

  it("samples the ship densely enough for smooth curves", () => {
    expect(maxStep(ship.track, hms(22, 32, 28) - 600, hms(22, 32, 28))).toBeLessThanOrEqual(1);
    expect(maxStep(ship.track, hms(22, 10, 46) - 300, hms(22, 32, 28) - 600)).toBeLessThanOrEqual(2);
    expect(maxStep(ship.track, 0, hms(22, 32, 28))).toBeLessThanOrEqual(30);
    expect(maxStep(booster.track, 360, lastT(booster.track))).toBeLessThanOrEqual(0.25);
  });

  it("is caught by the tower at T+22:32:28 (belly flop, then vertical)", () => {
    expect(lastT(ship.track)).toBe(hms(22, 32, 28));
    const end = at(ship.track, hms(22, 32, 28));
    expect(groundDistanceKm(end, PAD)).toBeLessThan(0.1);
    expect(end.altKm).toBeLessThan(0.15);
    expect(end.speedKmS).toBeLessThan(0.005);
    for (const t of [hms(22, 30, 30), hms(22, 31, 0), hms(22, 31, 40), hms(22, 32, 10)]) {
      expect(Math.abs(noseElevationDeg(ship.track, t))).toBeLessThan(15);
    }
    expect(noseElevationDeg(ship.track, hms(22, 32, 28))).toBeGreaterThan(80);
  });

  it("ends the booster at its offshore aim point after the aborted catch", () => {
    const end = lastT(booster.track);
    // engines off at T+6:35, FTS just above the water: impact ~T+6:36–6:38
    expect(end).toBeGreaterThan(395.5);
    expect(end).toBeLessThan(398.5);
    const last = at(booster.track, end);
    expect(Math.abs(last.altKm)).toBeLessThan(0.001);
    expect(last.lonDeg).toBeGreaterThan(PAD.lonDeg + 0.02);
    expect(groundDistanceKm(last, BOOSTER_END)).toBeLessThan(0.05);
    // no approach to the tower: from the landing burn on, the booster stays near the offshore point
    for (let t = 370; t <= end; t += 0.5) {
      const s = at(booster.track, t);
      expect(groundDistanceKm(s, PAD)).toBeGreaterThan(3);
      expect(groundDistanceKm(s, BOOSTER_END)).toBeLessThan(1);
    }
    // brief hover a few tens of metres above the water, ending with the shut-down at T+6:35
    for (const t of [391, 392, 393, 394, 395]) {
      const s = at(booster.track, t);
      expect(s.altKm).toBeGreaterThan(0.015);
      expect(s.altKm).toBeLessThan(0.06);
      // altitude held; the last few m/s of offshore drift are braked during the hover
      expect(Math.abs(s.altKm - at(booster.track, 393).altKm)).toBeLessThan(0.001);
      expect(s.speedKmS).toBeLessThan(0.008);
    }
    // falling after the shut-down
    expect(at(booster.track, 396.5).velocity).toBeDefined();
    expect(at(booster.track, 396.5).altKm).toBeLessThan(at(booster.track, 395.5).altKm);
    // vertical during the landing burn, hover and fall
    for (const t of [376, 385, 393, 397]) expect(noseElevationDeg(booster.track, t)).toBeGreaterThan(80);
  });

  it("flies a landing burn within Super Heavy's thrust and attitude limits", () => {
    let prev: ReturnType<typeof accelAt> | null = null;
    let maxJump = 0;
    for (let t = 370.5; t <= lastT(booster.track) - 0.5; t += 0.25) {
      const a = accelAt(booster.track, t, 0.25);
      const thrustV = a.av + G; // engines (and, early on, drag) carry this vertical part
      if (t >= 374 && t <= 395) {
        // kinematic horizontal acceleration (engine thrust ≈ 0.31 g plus the decaying drag of the first seconds)
        expect(a.ah / G).toBeLessThan(0.4);
        expect((Math.atan2(a.ah, thrustV) * 180) / Math.PI).toBeLessThan(20);
      }
      expect(Math.hypot(a.ah, thrustV) / G).toBeLessThan(4.5);
      if (prev) maxJump = Math.max(maxJump, Math.hypot(a.ah - prev.ah, a.av - prev.av));
      prev = a;
    }
    expect(maxJump / G).toBeLessThan(0.6); // continuous acceleration (0.25 s steps)
  });

  it("has no velocity jumps (plausible accelerations everywhere)", () => {
    const maxAccelG = (track: TrajectoryTrack, from: number, to: number, step: number) => {
      let worst = 0;
      let prev = at(track, from).velocity;
      for (let t = from + step; t <= to; t += step) {
        const v = at(track, t).velocity;
        worst = Math.max(worst, Math.hypot(v.x - prev.x, v.y - prev.y, v.z - prev.z) / step / 9.80665e-3);
        prev = v;
      }
      return worst;
    };
    expect(maxAccelG(booster.track, 0, lastT(booster.track), 0.5)).toBeLessThan(6);
    expect(maxAccelG(ship.track, 0, 2000, 0.5)).toBeLessThan(5);
    expect(maxAccelG(ship.track, 2000, hms(22, 0, 0), 5)).toBeLessThan(2);
    expect(maxAccelG(ship.track, hms(22, 0, 0), lastT(ship.track), 0.5)).toBeLessThan(4);
  });
});
